"""Export the response registry as one JSON Schema document.

Document shape (all keys sorted, two-space indent, trailing newline)::

    {
      "$defs": {"PublicHealthResponse": {...}, "ComponentCheck": {...}, ...},
      "$schema": "https://json-schema.org/draft/2020-12/schema",
      "additionalProperties": false,
      "description": "...",
      "properties": {"api_health": {"$ref": "#/$defs/PublicHealthResponse"}},
      "required": ["api_health"],
      "title": "JournalApi",
      "type": "object"
    }

The root object maps each route name to its response definition, so a
TypeScript generator emits one named type per definition plus a
``JournalApi`` interface keyed by route name. Per-property ``title`` keys
that Pydantic adds are stripped (they make generators emit throwaway
aliases); every definition's ``title`` is set to its ``$defs`` key because
that is what names the generated type.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, Any

from pydantic import TypeAdapter

from journal.api.contract.schemas import RESPONSE_SCHEMAS

if TYPE_CHECKING:
    from collections.abc import Mapping

SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
ROOT_TITLE = "JournalApi"
ROOT_DESCRIPTION = (
    "Response bodies of the journal REST API, keyed by route name. "
    "Generated by `uv run journal contract export` from "
    "server/src/journal/api/contract/schemas.py. Do not edit by hand."
)

# Keywords whose value is a single subschema / a list of subschemas /
# a mapping of name -> subschema. Used to strip titles only where
# `title` is a schema keyword, never where it is a property name.
_SUBSCHEMA_KEYS = ("items", "additionalProperties", "not", "contains")
_SUBSCHEMA_LIST_KEYS = ("anyOf", "oneOf", "allOf", "prefixItems")
_SUBSCHEMA_MAP_KEYS = ("properties", "patternProperties")


def _strip_titles(schema: Any) -> None:
    """Remove the ``title`` keyword from ``schema`` and every subschema."""
    if not isinstance(schema, dict):
        return
    schema.pop("title", None)
    for key in _SUBSCHEMA_KEYS:
        _strip_titles(schema.get(key))
    for key in _SUBSCHEMA_LIST_KEYS:
        for sub in schema.get(key, ()):
            _strip_titles(sub)
    for key in _SUBSCHEMA_MAP_KEYS:
        for sub in schema.get(key, {}).values():
            _strip_titles(sub)


def build_schema_document(
    schemas: Mapping[str, type] = RESPONSE_SCHEMAS,
) -> dict[str, Any]:
    """Build the contract document for ``schemas`` (route name -> TypedDict)."""
    route_names = sorted(schemas)
    refs, top = TypeAdapter.json_schemas(
        [(name, "serialization", TypeAdapter(schemas[name])) for name in route_names],
    )
    defs: dict[str, Any] = top.get("$defs", {})
    for def_name, definition in defs.items():
        _strip_titles(definition)
        # The title names the generated TS type: pin it to the $defs key,
        # which is unique (Pydantic's own titles may collide, and plain
        # aliases such as `type X = Literal[...]` get none).
        definition["title"] = def_name
    return {
        "$schema": SCHEMA_DIALECT,
        "title": ROOT_TITLE,
        "description": ROOT_DESCRIPTION,
        "type": "object",
        "properties": {name: refs[(name, "serialization")] for name in route_names},
        "required": route_names,
        "additionalProperties": False,
        "$defs": defs,
    }


def render_schema_document(schemas: Mapping[str, type] = RESPONSE_SCHEMAS) -> str:
    """Serialize the contract document deterministically (sorted keys, trailing newline)."""
    document = build_schema_document(schemas)
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def default_schema_path() -> Path:
    """Locate ``contract/api.schema.json`` at the monorepo root.

    Walks up from this file to the directory holding ``server/pyproject.toml``.
    Works for the editable install ``uv sync`` creates; a non-editable install
    (e.g. the Docker image) has no repo root, so pass an explicit path there.
    """
    for parent in Path(__file__).resolve().parents:
        if (parent / "server" / "pyproject.toml").is_file():
            return parent / "contract" / "api.schema.json"
    msg = (
        "Could not find the repo root (a directory containing server/pyproject.toml) "
        f"above {__file__}; pass an explicit output path."
    )
    raise FileNotFoundError(msg)


def write_schema(path: Path | None = None) -> Path:
    """Write the rendered contract to ``path`` (default: ``default_schema_path()``)."""
    target = path if path is not None else default_schema_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_schema_document(), encoding="utf-8", newline="\n")
    return target
